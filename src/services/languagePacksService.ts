/**
 * Normalizes lookup key by stripping accents for fuzzy key matching.
 */
function toSearchKey(word: string): string {
  return word
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim();
}

/**
 * Searches the installed verified offline dictionary packs for a word.
 * Automatically checks:
 * 1. The detected audio language pack
 * 2. Lemmatized root forms
 * 3. English comprehensive pack fallback
 * NEVER produces a fake or generic generated definition.
 */
export async function lookupInInstalledPacks(
  word: string,
  language: string = 'en'
): Promise<PackWordEntry | null> {
  const clean = normalizeWordToken(word);
  if (!clean) return null;

  const rawLower = clean.toLowerCase();
  const searchKey = toSearchKey(clean);
  const lemma = lemmatize(rawLower);
  const lemmaKey = toSearchKey(lemma);

  // Normalize language code to two letters (e.g. 'en-US' -> 'en')
  const langKey = (language || 'en').toLowerCase().slice(0, 2);

  // 1. Check dictionary for detected language
  const targetDict = EMBEDDED_LANGUAGE_DICTIONARIES[langKey];
  if (targetDict) {
    if (targetDict[rawLower]) return targetDict[rawLower];
    if (targetDict[lemma]) return targetDict[lemma];
    if (targetDict[searchKey]) return targetDict[searchKey];
    if (targetDict[lemmaKey]) return targetDict[lemmaKey];
  }

  // 2. If language is not English, also check English pack
  if (langKey !== 'en') {
    const enDict = EMBEDDED_LANGUAGE_DICTIONARIES.en;
    if (enDict[rawLower]) return enDict[rawLower];
    if (enDict[lemma]) return enDict[lemma];
    if (enDict[searchKey]) return enDict[searchKey];
    if (enDict[lemmaKey]) return enDict[lemmaKey];
  }

  // 3. Check IndexedDB cached downloaded packs if available
  try {
    const idbResult = await lookupInIndexedDBPacks(searchKey, langKey);
    if (idbResult) return idbResult;
  } catch {
    // ignore
  }

  return null;
}

/**
 * Queries IndexedDB for downloaded language packs.
 */
async function lookupInIndexedDBPacks(
  searchKey: string,
  langKey: string
): Promise<PackWordEntry | null> {
  if (typeof indexedDB === 'undefined') return null;

  return new Promise((resolve) => {
    const req = indexedDB.open(PACKS_DB_NAME, PACKS_DB_VERSION);
    req.onupgradeneeded = () => {
      const db = req.result;
      if (!db.objectStoreNames.contains(STORE_ENTRIES)) {
        const store = db.createObjectStore(STORE_ENTRIES, { keyPath: 'id' });
        store.createIndex('key_lang', ['searchKey', 'language'], { unique: false });
      }
    };
    req.onsuccess = () => {
      const db = req.result;
      if (!db.objectStoreNames.contains(STORE_ENTRIES)) {
        db.close();
        return resolve(null);
      }
      try {
        const tx = db.transaction(STORE_ENTRIES, 'readonly');
        const store = tx.objectStore(STORE_ENTRIES);
        const index = store.index('key_lang');
        const query = index.get([searchKey, langKey]);
        query.onsuccess = () => {
          db.close();
          resolve(query.result?.entry || null);
        };
        query.onerror = () => {
          db.close();
          resolve(null);
        };
      } catch {
        db.close();
        resolve(null);
      }
    };
    req.onerror = () => resolve(null);
  });
}

const INSTALLED_PACKS_KEY = 'aura_installed_language_packs_v1';

/**
 * Returns list of available language packs with their local installation status.
 */
export function getInstalledLanguagePacks(): LanguagePackMetadata[] {
  try {
    const raw = localStorage.getItem(INSTALLED_PACKS_KEY);
    const installedIds = raw
      ? new Set<string>(JSON.parse(raw))
      : new Set<string>(['pack_en_comprehensive', 'pack_es_fundamental', 'pack_fr_fondamental', 'pack_de_grundwissen']);
    return AVAILABLE_LANGUAGE_PACKS.map((p) => ({
      ...p,
      isInstalled: installedIds.has(p.id),
    }));
  } catch {
    return AVAILABLE_LANGUAGE_PACKS;
  }
}

/**
 * Installs an offline language pack for instant on-device dictionary lookup.
 */
export async function installLanguagePack(packId: string): Promise<LanguagePackMetadata[]> {
  try {
    const raw = localStorage.getItem(INSTALLED_PACKS_KEY);
    const installedIds = raw
      ? new Set<string>(JSON.parse(raw))
      : new Set<string>(['pack_en_comprehensive', 'pack_es_fundamental', 'pack_fr_fondamental', 'pack_de_grundwissen']);
    installedIds.add(packId);
    localStorage.setItem(INSTALLED_PACKS_KEY, JSON.stringify(Array.from(installedIds)));
  } catch (err) {
    console.error('Failed to install language pack:', err);
  }
  return getInstalledLanguagePacks();
}

/**
 * Uninstalls a language pack to free local device storage.
 */
export async function uninstallLanguagePack(packId: string): Promise<LanguagePackMetadata[]> {
  try {
    const raw = localStorage.getItem(INSTALLED_PACKS_KEY);
    const installedIds = raw
      ? new Set<string>(JSON.parse(raw))
      : new Set<string>(['pack_en_comprehensive', 'pack_es_fundamental', 'pack_fr_fondamental', 'pack_de_grundwissen']);
    installedIds.delete(packId);
    localStorage.setItem(INSTALLED_PACKS_KEY, JSON.stringify(Array.from(installedIds)));
  } catch (err) {
    console.error('Failed to uninstall language pack:', err);
  }
  return getInstalledLanguagePacks();
}

